def main():

    First_Num = int(input("Give me the first number: "))
    Second_Num = int(input("Give me the second number: "))
    print("Thank you!")

    print(str(First_Num), "+", str(Second_Num), "=", str(First_Num+Second_Num))
    print(str(First_Num), "-", str(Second_Num), "=", str(First_Num-Second_Num))
    print(str(First_Num), "/", str(Second_Num), "=", str(First_Num/Second_Num))
    print(str(First_Num), "*", str(Second_Num), "=", str(First_Num*Second_Num))

main()